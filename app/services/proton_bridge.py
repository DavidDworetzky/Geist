"""Guided Bridge setup and credential lifecycle for the bundled email server."""

import uuid
from contextlib import suppress

from app.models.database.mcp_server import (
    McpServerModel,
    create_mcp_server,
    update_mcp_server,
)
from app.models.proton_bridge import ProtonBridgeRequest
from app.services.email_credentials import EmailCredentialError, credentials
from app.services.email_mcp import EmailError, MailClient, validate_address


def connection_settings(
    request: ProtonBridgeRequest, existing: McpServerModel | None = None
) -> dict:
    values = request.model_dump(
        exclude={"name", "password", "recipient_allowlist", "max_writes_per_hour"}
    )
    for address in request.recipient_allowlist:
        validate_address(address)
    if request.password is not None and request.password.get_secret_value():
        password = request.password.get_secret_value()
    elif existing and existing.managed_email:
        password = credentials(existing.managed_email["credential_id"])
    else:
        raise EmailError("Paste the password generated by Proton Mail Bridge")
    values["password"] = password
    return values


def test_connection(settings: dict) -> None:
    try:
        MailClient(settings).test()
    except EmailError:
        raise
    except Exception as error:
        raise EmailError(
            "Cannot authenticate with Bridge. Keep Bridge running and check the ports, TLS modes, exported certificate, and Bridge password."
        ) from error


def test_saved_connection(server: McpServerModel) -> None:
    if not server.managed_email:
        raise EmailError("This server is not a bundled Bridge connection")
    settings = dict(server.managed_email)
    settings["password"] = credentials(settings.pop("credential_id"))
    test_connection(settings)


def save_connection(
    request: ProtonBridgeRequest, workspace_id: int, existing: McpServerModel | None = None
) -> McpServerModel:
    settings = connection_settings(request, existing)
    test_connection(settings)
    reference = uuid.uuid4().hex
    password = settings.pop("password")
    credentials(reference, password)
    settings["credential_id"] = reference
    # Keep delivery history across credential rotations and connection edits.
    previous = existing.managed_email if existing and existing.managed_email else {}
    settings["ledger_id"] = previous.get("ledger_id", previous.get("credential_id", reference))
    values = {
        "name": request.name,
        "transport": "stdio",
        "command": "geist-bundled-email",
        "args": [],
        "env": {},
        "headers": {},
        "url": None,
        "working_directory": None,
        "connector_kind": "proton",
        "account_label": request.username,
        "trusted": False,
        "security_required": True,
        "enabled": False,
        "recipient_allowlist": request.recipient_allowlist,
        "max_writes_per_hour": request.max_writes_per_hour,
        "timeout_seconds": 30.0,
        "managed_email": settings,
    }
    try:
        if existing:
            result = update_mcp_server(existing.mcp_server_id, values, workspace_id=workspace_id)
            if result is None:
                raise EmailError("Connection no longer exists")
        else:
            result = create_mcp_server(workspace_id, values)
    except Exception:
        credentials(reference, delete=True)
        raise
    if existing and existing.managed_email:
        with suppress(EmailCredentialError):
            credentials(existing.managed_email["credential_id"], delete=True)
    return result
